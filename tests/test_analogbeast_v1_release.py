#!/usr/bin/env python3
"""Read-only source checks for analogBEAST v1.0 release branding.
No device access; use after installer and before JieLi build.
"""
import ast
import importlib.util
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def get(rel):return (ROOT/rel).read_text(encoding='utf8')
fw=get('firmware/src/felucca.c')
assert '#define FELUCCA_ID "FM-1_901"' in fw
assert '#define FELUCCA_VERSION "v1.0"' in fw
assert '#define AB_BRAND_NAME "analogBEAST"' in fw
usb=get('firmware/src/usb.c')
start=usb.index('/* USB product string: analogBEAST')
part=usb[start:usb.index('#else',start)]
nums=re.findall(r"'([^']+)'|(?<![\w])([0-9]+)(?=\s*[,}])",part)
arr=bytes([ord(a) if a else int(n) for a,n in nums])
assert arr[0]==len(arr)==24 and arr[1]==3,arr
assert arr[2:].decode('utf-16le')=='analogBEAST'
assert '#ifdef FELUCCA_LOADER' in usb and 'Felucca' not in part
assert 'FELUCCA_USB_PID' in usb and '0x09, 0x12' in usb
assert 'AB_BRAND_NAME, FELUCCA_VERSION' in get('firmware/src/ui_draw.c')
assert 'GOLANA ? AB_BRAND_NAME' in get('firmware/src/ui_menu.c')
assert 'ed_str(AB_BRAND_NAME " " FELUCCA_VERSION, 24)' in get('firmware/src/editor.c')
assert 'con_puts(AB_BRAND_NAME " ")' in get('firmware/src/console.c')
b=get('tools/build.py')
assert 'PRODUCT = "FM-1_901"' in b
assert 'analogBEAST-v1.0.fwsc' in b
assert 'if not a.release:' in b
assert 'branded.write_bytes(pkg)' in b
assert 'PRODUCT = "FM-1_9" + m[1] + m[2]' in b  # --release would change ID; don't call it
installer=get('tools/fm1_install.py')
assert 'analogbeast' in installer[installer.index('PORT_RE'):installer.index('PORT_RE')+160]
s=get('tools/analogbeast_v5_patterns.py')
assert "default='analogBEAST 3'" in s and "default='analogBEAST 4'" in s
print('PASS: USB UTF-16 descriptor analogBEAST, legacy update-loader name unchanged')
print('PASS: splash/about/editor/console show analogBEAST v1.0')
print('PASS: FM-1_901 unchanged, branded package alias generated by normal build')
print('PASS: updater detects analogBEAST ports; E-H importer defaults updated')
